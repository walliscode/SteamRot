namespace steamrot::tests {

/////////////////////////////////////////////////
/// @struct SceneSnapshot
/// @brief Complete scene snapshot for testing.
///
/// Captures both metadata (via SceneInfo) and the full entity state
/// (via EntityMemoryPool) for test validation. This is specifically
/// for the test harness data bank.
/////////////////////////////////////////////////
struct SceneSnapshot {
  /////////////////////////////////////////////////
  /// @brief Scene metadata (id and type)
  /////////////////////////////////////////////////
  SceneInfo scene_info;

  /////////////////////////////////////////////////
  /// @brief Full entity memory pool snapshot
  /////////////////////////////////////////////////
  EntityMemoryPool entity_memory_pool;
};

} // namespace steamrot::tests
