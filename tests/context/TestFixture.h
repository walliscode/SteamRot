#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "DataAccessFactory.h"
#include "EngineResources.h"
#include "EntityManager.h"
#include "GameContext.h"
#include "SceneContext.h"
#include <SFML/Graphics/RenderTexture.hpp>
#include <memory>

namespace steamrot::tests {

/////////////////////////////////////////////////
/// @class TestFixture
/// @brief Provides mock game and scene contexts for unit testing.
///
/// TestFixture owns all core objects needed for testing:
/// - GameCore (window, event handler, asset manager)
/// - SceneCore (render texture)
/// - EntityManager (entity pool, archetype manager)
///
/// These are used to create GameContext and SceneContext objects
/// that can be passed to classes under test (Logic, SceneFactory, etc.)
///
/// Usage:
/// @code
/// TEST_CASE("MyTest", "[unit]") {
///   TestFixture fixture;
///   fixture.Initialize();
///   auto& game_context = fixture.GetGameContext();
///   // Use game_context for testing...
/// }
/// @endcode
/////////////////////////////////////////////////
class TestFixture {
public:
  /////////////////////////////////////////////////
  /// @brief Default constructor for TEST scene type
  /////////////////////////////////////////////////
  TestFixture();

  /////////////////////////////////////////////////
  /// @brief Constructor with specific scene type
  ///
  /// @param scene_type Scene type to configure for
  /////////////////////////////////////////////////
  explicit TestFixture(SceneType scene_type);

  /////////////////////////////////////////////////
  /// @brief Destructor
  /////////////////////////////////////////////////
  ~TestFixture();

  /////////////////////////////////////////////////
  /// @brief Initialize all resources
  ///
  /// Creates the window, render texture, and other resources.
  /// Must be called before using GetGameContext() or GetSceneContext()
  /// if full initialization is required.
  /////////////////////////////////////////////////
  void Initialize();

  /////////////////////////////////////////////////
  /// @brief Initialize all resources (typo-compatible alias)
  ///
  /// @deprecated Use Initialize() instead
  /////////////////////////////////////////////////
  void Intialize() { Initialize(); }

  /////////////////////////////////////////////////
  /// @brief Get reference to GameContext
  ///
  /// @return Reference to the GameContext for testing
  /////////////////////////////////////////////////
  GameContext &GetGameContext();

  /////////////////////////////////////////////////
  /// @brief Get reference to SceneContext
  ///
  /// @return Reference to the SceneContext for testing
  /////////////////////////////////////////////////
  SceneContext &GetSceneContext();

  /////////////////////////////////////////////////
  /// @brief Get the current scene type
  ///
  /// @return The SceneType this fixture was created with
  /////////////////////////////////////////////////
  SceneType GetSceneType() const;

private:
  /////////////////////////////////////////////////
  /// @brief Scene type for this fixture
  /////////////////////////////////////////////////
  SceneType m_scene_type;

  /////////////////////////////////////////////////
  /// @brief Flag indicating if Initialize() has been called
  /////////////////////////////////////////////////
  bool m_initialized{false};

  /////////////////////////////////////////////////
  /// @brief Data access factory for providing data providers
  /////////////////////////////////////////////////
  DataAccessFactory m_data_access_factory;

  /////////////////////////////////////////////////
  /// @brief Engine resources containing window, event handler, etc.
  /////////////////////////////////////////////////
  EngineResources m_engine_resources;

  /////////////////////////////////////////////////
  /// @brief Scene render texture
  /////////////////////////////////////////////////
  sf::RenderTexture m_scene_texture;

  /////////////////////////////////////////////////
  /// @brief Entity manager with entity pool and archetypes
  /////////////////////////////////////////////////
  std::unique_ptr<EntityManager> m_entity_manager;

  /////////////////////////////////////////////////
  /// @brief GameContext created from engine resources
  /////////////////////////////////////////////////
  std::unique_ptr<GameContext> m_game_context;

  /////////////////////////////////////////////////
  /// @brief SceneContext created from cores and entity manager
  /////////////////////////////////////////////////
  std::unique_ptr<SceneContext> m_scene_context;

  /////////////////////////////////////////////////
  /// @brief Create core objects without full initialization
  /////////////////////////////////////////////////
  void CreateCores();

  /////////////////////////////////////////////////
  /// @brief Create context objects from cores
  /////////////////////////////////////////////////
  void CreateContexts();
};

} // namespace steamrot::tests
