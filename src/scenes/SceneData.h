
/////////////////////////////////////////////////
/// @class SceneData
/// @brief Captures essential information about a Scene.
///
/// Contains required identifying information (UUID, SceneType) and optional
/// data container snapshots for EntityMemoryPool, Archetypes, EventBus, etc.
/////////////////////////////////////////////////

/////////////////////////////////////////////////
/// Preprocessor Directives
/////////////////////////////////////////////////
#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "EventHandler.h"
#include "containers.h"
#include "entity_types.h"
#include "scene_change_packet_generated.h"
#include "uuid.h"
#include <optional>
#include <unordered_map>

namespace steamrot {
struct SceneData {
  /////////////////////////////////////////////////
  /// @brief Unique identifier for the Scene (required)
  /////////////////////////////////////////////////
  uuids::uuid id;

  /////////////////////////////////////////////////
  /// @brief Scene type identifier (required)
  /////////////////////////////////////////////////
  SceneType type;

  /////////////////////////////////////////////////
  /// @brief Optional snapshot of EntityMemoryPool
  /////////////////////////////////////////////////
  std::optional<EntityMemoryPool> entity_memory_pool;

  /////////////////////////////////////////////////
  /// @brief Optional snapshot of Archetypes
  /////////////////////////////////////////////////
  std::optional<std::unordered_map<ArchetypeID, Archetype>> archetypes;

  /////////////////////////////////////////////////
  /// @brief Optional snapshot of the global_event_bus
  /////////////////////////////////////////////////
  std::optional<EventBus> global_event_bus;

  /////////////////////////////////////////////////
  /// @brief Optional snapshot of the waiting_room
  /////////////////////////////////////////////////
  std::optional<EventBus> waiting_room;
};
} // namespace steamrot
