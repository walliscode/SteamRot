#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "EventPacket.h"
#include <optional>

namespace steamrot {

/////////////////////////////////////////////////
/// @struct SubscriberConfig
/// @brief Configuration data for creating a Subscriber
///
/// This is an intermediate struct used to configure Subscriber instances.
/// It contains the same data as Subscriber but is used for initialization.
/////////////////////////////////////////////////
struct SubscriberConfig {

/////////////////////////////////////////////////
  /// @brief Indicates whether the subscriber should start active.
/////////////////////////////////////////////////
  bool active{false};

/////////////////////////////////////////////////
  /// @brief Event type that this subscriber listens for.
/////////////////////////////////////////////////
  EventType trigger_event_type{EventType::EventType_NONE};

/////////////////////////////////////////////////
  /// @brief If set, the subscriber will only be activated if the event data
  /// matches this trigger data.
/////////////////////////////////////////////////
  std::optional<EventData> trigger_event_data{std::nullopt};
};

} // namespace steamrot
