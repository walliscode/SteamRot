#include "ArchetypeManager.h"
#include "containers.h"
#include <SFML/Graphics/RenderTexture.hpp>

namespace steamrot {

/////////////////////////////////////////////////
/// @struct SceneResources
/// @brief Contains all scene-level resources (no references to other Resources)
///
/// This struct holds the actual resource objects at the scene level.
/// Resources are standalone objects without cross-references.
/////////////////////////////////////////////////
struct SceneResources {
  /////////////////////////////////////////////////
  /// @brief Entity memory pool for the scene
  /////////////////////////////////////////////////
  EntityMemoryPool scene_entities;

  /////////////////////////////////////////////////
  /// @brief Archetype manager for organizing entities by archetype
  /////////////////////////////////////////////////
  ArchetypeManager archetype_manager;

  /////////////////////////////////////////////////
  /// @brief Render texture for the scene
  /////////////////////////////////////////////////
  sf::RenderTexture scene_texture;

  /////////////////////////////////////////////////
  /// @brief Constructor that initializes archetype_manager with scene_entities reference
  /////////////////////////////////////////////////
  SceneResources() : archetype_manager(scene_entities) {}
};

} // namespace steamrot
