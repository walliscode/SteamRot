#include "UIStyle.h"
#include <SFML/Graphics/RenderTexture.hpp>

namespace steamrot {
namespace logic {
namespace ui {
namespace render {

/////////////////////////////////////////////////
/// @brief Context object for UI rendering operations
///
/// Groups all parameters needed for rendering UI elements into a single
/// cohesive object, reducing parameter passing overhead and improving
/// maintainability.
/////////////////////////////////////////////////
struct UIRenderContext {
  /////////////////////////////////////////////////
  /// @brief Reference to the render texture to draw to
  /////////////////////////////////////////////////
  sf::RenderTexture &texture;

  /////////////////////////////////////////////////
  /// @brief Reference to the UI style to use for rendering
  /////////////////////////////////////////////////
  const UIStyle &style;
};

} // namespace render
} // namespace ui
} // namespace logic
} // namespace steamrot
