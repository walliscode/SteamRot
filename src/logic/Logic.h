#include "SceneContext.h"
#include "Subscriber.h"
#include <memory>
namespace steamrot {

using EntityIndicies = std::vector<size_t>;

/////////////////////////////////////////////////
/// @class Logic
/// @brief Abstract base class for all logic processing in the game.
///
/////////////////////////////////////////////////
class Logic {
protected:
  /////////////////////////////////////////////////
  /// @brief Collates all the logic functions in a single convenience function.
  /////////////////////////////////////////////////
  virtual void ProcessLogic() = 0;

  /////////////////////////////////////////////////
  /// @brief Contains an instance of the SceneContext struct.
  /////////////////////////////////////////////////
  SceneContext m_scene_context;

  /////////////////////////////////////////////////
  /// @brief A vector of shared pointers to Subscriber objects.
  /////////////////////////////////////////////////
  std::vector<std::shared_ptr<Subscriber>> m_subscribers;

public:
  /////////////////////////////////////////////////
  /// @brief Constructor for the Logic class.
  ///
  /// @param scene_context Instance of the SceneContext struct
  /////////////////////////////////////////////////
  Logic(const SceneContext scene_context);

  /////////////////////////////////////////////////
  /// @brief Default destructor for the Logic class.
  /////////////////////////////////////////////////
  virtual ~Logic() = default;

  /////////////////////////////////////////////////
  /// @brief Interface function to run the logic processing.
  ///
  /// This function should be the only interface function called by the game
  /// loop. Here we can add in any frequency modifiers or other logic that needs
  /// to be run
  /////////////////////////////////////////////////
  void RunLogic();

  /////////////////////////////////////////////////
  /// @brief A view accessor for the subscribers vector.
  /////////////////////////////////////////////////
  const std::vector<std::shared_ptr<Subscriber>> &GetSubscribers() const;

  /////////////////////////////////////////////////
  /// @brief  A contiainer function to process all subscribers on this logic
  /// object.
  /////////////////////////////////////////////////
  // virtual void ProcessSubscribers() = 0;
};
} // namespace steamrot
