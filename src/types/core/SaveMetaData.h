/////////////////////////////////////////////////
/// @file
/// @brief Defines the SaveMetaData structure.
/////////////////////////////////////////////////

/////////////////////////////////////////////////
/// Preprocessor Directives
/////////////////////////////////////////////////
#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "uuid.h"
#include <string>

namespace steamrot {

/////////////////////////////////////////////////
/// @class SaveMetaData
/// @brief Contains metadata about a save state.
///
/////////////////////////////////////////////////
struct SaveMetaData {

  /////////////////////////////////////////////////
  /// @brief The file prefix UUID for the save for easy identification.
  /////////////////////////////////////////////////
  uuids::uuid file_id;

  /////////////////////////////////////////////////
  /// @brief The name of the save.
  /////////////////////////////////////////////////
  std::string save_name;
};
} // namespace steamrot
