#include <string>

namespace steamrot {

/////////////////////////////////////////////////
/// @class SelectAndPlaceState
/// @brief Tracks the current state of the select-and-place workflow.
///
/// Holds which item is currently selected for placement. This struct
/// is designed to be owned by a SelectAndPlaceLogic instance, but can
/// also be embedded in other contexts that need to track selection state.
/////////////////////////////////////////////////
struct SelectAndPlaceState {

  /////////////////////////////////////////////////
  /// @brief True when an item has been selected and is awaiting placement
  /////////////////////////////////////////////////
  bool is_item_selected{false};

  /////////////////////////////////////////////////
  /// @brief Name of the item currently selected for placement
  /////////////////////////////////////////////////
  std::string selected_item_name;

  /////////////////////////////////////////////////
  /// @brief Category of the selected item (e.g. "fragment", "joint")
  /////////////////////////////////////////////////
  std::string selected_item_type;

  /////////////////////////////////////////////////
  /// @brief Clear all selection state, returning to the idle state
  /////////////////////////////////////////////////
  void Clear() {
    is_item_selected = false;
    selected_item_name.clear();
    selected_item_type.clear();
  }
};

} // namespace steamrot
