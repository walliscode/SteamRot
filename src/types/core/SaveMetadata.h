#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include <cstdint>
#include <string>

namespace steamrot {

/////////////////////////////////////////////////
/// @struct SaveMetadata
/// @brief Metadata about a save file for UI display and management.
///
/// SaveMetadata contains non-gameplay information about a save file,
/// such as display name, timestamps, and version information.
/// This data can be loaded independently from the full save data
/// for save slot selection screens.
/////////////////////////////////////////////////
struct SaveMetadata {
  /////////////////////////////////////////////////
  /// @brief Display name for the save slot shown to the player
  /////////////////////////////////////////////////
  std::string save_name;

  /////////////////////////////////////////////////
  /// @brief Timestamp when save was created (ISO 8601 format)
  /////////////////////////////////////////////////
  std::string created_at;

  /////////////////////////////////////////////////
  /// @brief Timestamp when save was last modified (ISO 8601 format)
  /////////////////////////////////////////////////
  std::string last_modified;

  /////////////////////////////////////////////////
  /// @brief Game version that created this save (e.g., "1.0.0")
  /////////////////////////////////////////////////
  std::string game_version;

  /////////////////////////////////////////////////
  /// @brief Total play time in seconds
  /////////////////////////////////////////////////
  uint64_t play_time_seconds{0};

  /////////////////////////////////////////////////
  /// @brief Save slot identifier (0-based index)
  /////////////////////////////////////////////////
  uint32_t slot_index{0};
};

} // namespace steamrot
