/////////////////////////////////////////////////
/// Preprocessor Directives
/////////////////////////////////////////////////
#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "FailInfo.h"
#include "GrimoireMachina.h"
#include <expected>
#include <variant>

namespace steamrot {

/////////////////////////////////////////////////
/// @class IGrimoireMachinaProvider
/// @brief Class to provider and/or configure GrimoireMachina data structures.
///
/////////////////////////////////////////////////
class IGrimoireMachinaProvider {

public:
  /////////////////////////////////////////////////
  /// @brief Virtual destructor.
  /////////////////////////////////////////////////
  virtual ~IGrimoireMachinaProvider() = default;

  /////////////////////////////////////////////////
  /// @brief Provide a configured GrimoireMachina object.
  /////////////////////////////////////////////////
  virtual std::expected<GrimoireMachina, FailInfo>
  CreateGrimoireMachina() const = 0;

  /////////////////////////////////////////////////
  /// @brief Configure the provided GrimoireMachina object.
  ///
  /// @param grimoire_machina GrimoireMachina object to configure.
  /////////////////////////////////////////////////
  std::expected<std::monostate, FailInfo> virtual ConfigureGrimoireMachina(
      GrimoireMachina &grimoire_machina) const = 0;
};

} // namespace steamrot
