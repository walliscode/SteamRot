#pragma once

////////////////////////////////////////////////////////////
/// Headers
////////////////////////////////////////////////////////////
#include "FailInfo.h"
#include <SFML/Graphics/Font.hpp>
#include <expected>
#include <memory>
#include <string>

namespace steamrot {

////////////////////////////////////////////////////////////
/// @class IFontProvider
/// @brief Interface for providing font resources
///
/// This interface abstracts font access, allowing configurators
/// to load fonts without depending directly on AssetManager.
////////////////////////////////////////////////////////////
class IFontProvider {
public:
  ////////////////////////////////////////////////////////////
  /// @brief Virtual destructor
  ////////////////////////////////////////////////////////////
  virtual ~IFontProvider() = default;

  ////////////////////////////////////////////////////////////
  /// @brief Get a font by name
  ///
  /// @param font_name Name of the font to retrieve
  /// @return Shared pointer to the font, or error if not found
  ////////////////////////////////////////////////////////////
  virtual std::expected<std::shared_ptr<const sf::Font>, FailInfo>
  GetFont(const std::string &font_name) const = 0;
};

} // namespace steamrot
