////////////////////////////////////////////////////////////
/// @file
/// @brief Interface for loading input-action configuration data.
////////////////////////////////////////////////////////////

#pragma once

////////////////////////////////////////////////////////////
/// Headers
////////////////////////////////////////////////////////////
#include "FailInfo.h"
#include "InputActionRegistry.h"
#include <expected>

namespace steamrot {

////////////////////////////////////////////////////////////
/// @class IInputActionConfigProvider
/// @brief Interface for building an InputActionRegistry from a data source.
////////////////////////////////////////////////////////////
class IInputActionConfigProvider {
public:
  ////////////////////////////////////////////////////////////
  /// @brief Virtual destructor.
  ////////////////////////////////////////////////////////////
  virtual ~IInputActionConfigProvider() = default;

  ////////////////////////////////////////////////////////////
  /// @brief Build and return an InputActionRegistry from the data source.
  ///
  /// @return Populated registry on success, FailInfo on error.
  ////////////////////////////////////////////////////////////
  virtual std::expected<InputActionRegistry, FailInfo>
  CreateInputActionRegistry() const = 0;
};

} // namespace steamrot
