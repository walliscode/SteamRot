/////////////////////////////////////////////////
/// @file
/// @brief Declaration of the EngineData struct used for storing engine-related
/// data.
/////////////////////////////////////////////////

/////////////////////////////////////////////////
/// Preprocessor Directives
/////////////////////////////////////////////////
#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////

#include "AssetConfig.h"
#include "EngineConfig.h"
#include "EngineResourcesConfig.h"
#include "EngineState.h"

namespace steamrot {

/////////////////////////////////////////////////
/// @class EngineData
/// @brief A container struct for all the data an engine needs to operate.
///
/////////////////////////////////////////////////
struct EngineData {

  /////////////////////////////////////////////////
  /// @brief Configuration data for the engine resources.
  /////////////////////////////////////////////////
  EngineResourcesConfig engine_resources_config;

  /////////////////////////////////////////////////
  /// @brief Data for the state of the engine.
  /////////////////////////////////////////////////
  EngineState engine_state;

  /////////////////////////////////////////////////
  /// @brief Data for the engine configuration.
  /////////////////////////////////////////////////
  EngineConfig engine_config;

  /////////////////////////////////////////////////
  /// @brief Data for the initial asset configuration, used by the AssetManager
  /////////////////////////////////////////////////
  AssetConfig initial_asset_config;
};
} // namespace steamrot
