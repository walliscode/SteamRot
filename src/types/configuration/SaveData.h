/////////////////////////////////////////////////
/// @file
/// @brief Defines the SaveData struct used for saving game state.
/////////////////////////////////////////////////

/////////////////////////////////////////////////
/// Preprocessor Directives
/////////////////////////////////////////////////
#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "EngineSnapshot.h"
#include "SaveMetaData.h"

namespace steamrot {

/////////////////////////////////////////////////
/// @class SaveData
/// @brief Contains all information for a single save state.
/////////////////////////////////////////////////
struct SaveData {

  /////////////////////////////////////////////////
  /// @brief information about the save itself (timestamp, version, etc.)
  /////////////////////////////////////////////////
  SaveMetaData meta_data;

  /////////////////////////////////////////////////
  /// @brief Contains a snapshot of the engine state at the time of saving
  /////////////////////////////////////////////////
  EngineSnapshot engine_snapshot;
};
} // namespace steamrot
