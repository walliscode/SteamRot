#include <string>

namespace steamrot {

/////////////////////////////////////////////////
/// @class TestMetaData
/// @brief Contains metadata about a test
/////////////////////////////////////////////////
struct TestMetaData {

  /////////////////////////////////////////////////
  /// @brief The name of the test
  /////////////////////////////////////////////////
  std::string test_name{};

  /////////////////////////////////////////////////
  /// @brief Human readable description of the test
  /////////////////////////////////////////////////
  std::string test_description{};

  /////////////////////////////////////////////////
  /// @brief Bool that indicates whether the test is expected to pass
  /////////////////////////////////////////////////
  bool will_pass{true};
};
} // namespace steamrot
