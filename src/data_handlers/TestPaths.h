#pragma once

/////////////////////////////////////////////////
/// Headers
/////////////////////////////////////////////////
#include "PathProvider.h"
#include <filesystem>

namespace steamrot {

/////////////////////////////////////////////////
/// @class TestPaths
/// @brief Provides paths for test data files
///
/// TestPaths inherits from PathProvider and returns paths pointing to
/// the test data directory (tests/data).
/////////////////////////////////////////////////
class TestPaths : public PathProvider {

public:
  /////////////////////////////////////////////////
  /// @brief Default constructor
  /////////////////////////////////////////////////
  TestPaths() = default;

  /////////////////////////////////////////////////
  /// @brief Virtual destructor
  /////////////////////////////////////////////////
  ~TestPaths() override = default;

  /////////////////////////////////////////////////
  /// @brief Provides the test data directory path
  ///
  /// @return std::filesystem::path The test data directory path
  /////////////////////////////////////////////////
  std::filesystem::path GetDataDirectory() const override;
};

} // namespace steamrot
