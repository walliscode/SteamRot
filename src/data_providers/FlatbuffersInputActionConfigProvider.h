////////////////////////////////////////////////////////////
/// @file
/// @brief FlatBuffers implementation of IInputActionConfigProvider.
////////////////////////////////////////////////////////////

#pragma once

////////////////////////////////////////////////////////////
/// Headers
////////////////////////////////////////////////////////////
#include "FlatbuffersDataLoader.h"
#include "IInputActionConfigProvider.h"
#include <expected>

namespace steamrot {

////////////////////////////////////////////////////////////
/// @class FlatbuffersInputActionConfigProvider
/// @brief Builds an InputActionRegistry from FlatBuffers binary data.
////////////////////////////////////////////////////////////
class FlatbuffersInputActionConfigProvider : public IInputActionConfigProvider {
private:
  ////////////////////////////////////////////////////////////
  /// @brief Instance of FlatbuffersDataLoader for loading data.
  ////////////////////////////////////////////////////////////
  FlatbuffersDataLoader m_loader;

public:
  ////////////////////////////////////////////////////////////
  /// @brief Default constructor.
  ////////////////////////////////////////////////////////////
  FlatbuffersInputActionConfigProvider() = default;

  ////////////////////////////////////////////////////////////
  /// @brief Build and return an InputActionRegistry from FlatBuffers data.
  ///
  /// Loads the default input-action config binary and runs the configure
  /// free functions to produce a ready-to-use registry.
  ///
  /// @return Populated registry on success, FailInfo on error.
  ////////////////////////////////////////////////////////////
  std::expected<InputActionRegistry, FailInfo>
  CreateInputActionRegistry() const override;
};

} // namespace steamrot
